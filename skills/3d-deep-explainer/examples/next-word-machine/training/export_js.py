import json, sys
d = json.load(open("model.json"))
out = sys.argv[1] if len(sys.argv) > 1 else "weights.js"  # e.g. ../weights.js
hdr = ("/* The Next-Word Machine — real trained weights (PyTorch, Adam, seeded). Generated by train.py; do not edit.\n"
       "   vocab V=%d, d=8, 2 heads x d_head 4, 2 layers, learned positions (max 10), ReLU FFN 16 / MoE 4x8 top-2.\n"
       "   Plain train cross-entropy: dense %.4f, MoE %.4f nats/token (corpus entropy floor %.4f). */\n") % (
       len(d["vocab"]), d["dense_train_loss"], d["moe_train_loss"], d["entropy_floor"])
open(out, "w").write(hdr + "window.NWM_DATA = " + json.dumps(d, separators=(",", ":")) + ";\n")
print("wrote", out)
